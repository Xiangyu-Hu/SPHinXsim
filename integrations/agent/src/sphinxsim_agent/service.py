"""One domain dispatcher for the public CLI and MCP tools.

The workspace and optional desktop access are chosen by the process owner,
never by a discovered tool's arguments. No arbitrary shell/code is accepted.
"""
import json
import uuid

from jsonschema import Draft202012Validator

from .jobs import JobStore

from importlib.resources import files
CONTRACT = json.loads(files("sphinxsim_agent").joinpath("schemas/contracts-v1.json").read_text())
OBJECT = {"type": "object"}
PATH = {"type": "string", "minLength": 1, "maxLength": 240}
JOB = {"type": "string", "format": "uuid"}


def schema(properties, required=()):
    return {"type": "object", "properties": properties, "required": list(required), "additionalProperties": False}


TOOLS = {
    "capabilities": ("Describe native schema/routing evidence and CAD limits; not physical certification.", schema({"includeSchema": {"type": "boolean", "default": False}})),
    "validate": ("Validate native configuration schema and routing; submit additionally validates project assets. No desktop or GPU is started.", schema({"entry": PATH}, ["entry"])),
    "compile": ("Compile explicit unit quantities in the native configuration; review before applying.", schema({"specification": {"type": "object", "properties": {"version": {"const": 1}, "configuration": OBJECT}, "required": ["version", "configuration"], "additionalProperties": False}}, ["specification"])),
    "geometry_generate": ("Generate STL/STEP asynchronously from a bounded CAD recipe, without arbitrary code.", schema({"recipe": CONTRACT["$defs"]["cadRecipe"]}, ["recipe"])),
    "submit": ("Freeze a project and submit geometry, retained particles or formal simulation locally. Returns a job immediately.", schema({"entry": PATH, "kind": {"enum": ["geometry", "particles", "run"]}, "leaseSeconds": {"type": "integer", "minimum": 1, "maximum": 86400}, "refreshSeconds": {"type": "integer", "minimum": 1, "maximum": 3600}, "wallSeconds": {"type": "integer", "minimum": 1, "maximum": 259200}}, ["entry"])),
    "job_status": ("Read persistent job state; reconnecting does not repeat submission.", schema({"jobId": JOB}, ["jobId"])),
    "job_logs": ("Read at most the last 16 KiB of native logs.", schema({"jobId": JOB}, ["jobId"])),
    "job_continue": ("Continue the same frozen particle instance within its lease; repeated requests are idempotent.", schema({"jobId": JOB}, ["jobId"])),
    "job_cancel": ("Explicitly cancel a calculation. Disconnecting or stopping automation does not cancel it.", schema({"jobId": JOB}, ["jobId"])),
    "results_inspect": ("Verify immutable output hashes and report measured quality limits; execution success is not physical certification.", schema({"jobId": JOB}, ["jobId"])),
    "desktop": ("Use the optional live native desktop. Stop fences desktop automation, including active actions; it does not cancel calculations.", schema({"operation": {"enum": ["status", "observe", "action", "application", "display", "stop"]}, "tool": {"type": "string"}, "command": {"enum": ["capabilities", "compile", "validate", "update", "apply_configuration", "save", "preview", "particles", "continue", "cancel", "screenshot", "geometry_generate", "geometry_status", "geometry_cancel"]}, "arguments": OBJECT}, ["operation"])),
}


class Service:
    def __init__(self, root, *, desktop=False, automation_scope=None):
        self.jobs = JobStore(root)
        self.desktop = desktop
        # Opaque automation scope generated by the trusted process, not the model.
        if automation_scope is None:
            self.automation = uuid.uuid4().hex + uuid.uuid4().hex
        else:
            import hashlib
            self.automation = hashlib.sha256((str(self.jobs.root) + "\0" + automation_scope).encode()).hexdigest()

    def call(self, name, arguments):
        if name not in TOOLS:
            raise ValueError("Unknown operation")
        Draft202012Validator(TOOLS[name][1]).validate(arguments)
        if len(json.dumps(arguments, allow_nan=False).encode()) > 1 << 20:
            raise ValueError("Tool input exceeds 1 MiB")
        if name == "capabilities":
            from .physics import catalog
            from .modeling import recipe_contract
            result = dict(catalog())
            if not arguments.get("includeSchema"):
                result.pop("schema", None)
            return {"protocolVersion": 1, **result, "modeling": recipe_contract(),
                "execution": {"backend": "local", "maxActiveJobs": 4, "resourceLimits": "CPU/memory/GPU isolation must be supplied by the process owner"},
                "desktop": {"enabled": self.desktop, "transport": "local-private-rpc", "computerUse": "optional-cua-envelope"}}
        if name == "compile":
            from .physics import compile_config
            config, report = compile_config(arguments["specification"])
            return {"configuration": config, "report": report, "applied": False}
        if name == "validate":
            from .physics import check_config
            path = self.jobs.path(arguments["entry"])
            if path.stat().st_size > 1 << 20:
                raise ValueError("Entry configuration exceeds 1 MiB")
            config, report = check_config(json.loads(path.read_text()))
            return {"configuration": config, "report": report}
        if name == "geometry_generate":
            return self.jobs.generate(arguments["recipe"])
        if name == "submit":
            return self.jobs.submit(arguments["entry"], kind=arguments.get("kind", "run"),
                lease_seconds=arguments.get("leaseSeconds", 600), refresh_seconds=arguments.get("refreshSeconds", 10), wall_seconds=arguments.get("wallSeconds", 3600))
        if name == "desktop":
            if not self.desktop:
                raise ValueError("Desktop access was not enabled by the process owner")
            from .desktop.control_client import request
            state = request({"operation": "status"})
            return request({**arguments, "version": state["version"], "automationId": self.automation})
        methods = {"job_status": self.jobs.status, "job_logs": self.jobs.logs, "job_continue": self.jobs.continue_job,
                   "job_cancel": self.jobs.cancel, "results_inspect": self.jobs.results}
        return methods[name](arguments["jobId"])
